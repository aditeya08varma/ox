func TestRemoveRepoHooks_DryRunMixed(t *testing.T) {
	tmpDir := t.TempDir()
	hooksDir := filepath.Join(tmpDir, ".git", "hooks")
	require.NoError(t, os.MkdirAll(hooksDir, 0755))

	// mixed hook should be reported but not modified in dry run
	content := "#!/bin/sh\n# husky\nnpm test\n\n# ox pre-commit hook\nmake lint\n"
	hookPath := filepath.Join(hooksDir, "pre-commit")
	require.NoError(t, os.WriteFile(hookPath, []byte(content), 0755))

	err := RemoveRepoHooks(tmpDir, true)
	require.NoError(t, err)

	// file should be unchanged
	got, err := os.ReadFile(hookPath)
	require.NoError(t, err)
	assert.Equal(t, content, string(got))
}

func TestRemoveSageoxSections_PreservesFilePermissions(t *testing.T) {
	tmpFile := filepath.Join(t.TempDir(), "hook")
	content := "#!/bin/sh\n# ox pre-commit hook\nmake lint\n\n\n# user section\necho done\n"
	require.NoError(t, os.WriteFile(tmpFile, []byte(content), 0755))

	err := removeSageoxSections(tmpFile)
	require.NoError(t, err)

	info, err := os.Stat(tmpFile)
	require.NoError(t, err)
	// verify executable bit preserved
	assert.NotEqual(t, os.FileMode(0), info.Mode()&0100, "owner execute bit should be preserved")
}

func TestRemoveSageoxSections_SectionEndAfterDoubleBlankLine(t *testing.T) {
	// sageox section followed by 2+ blank lines should end the section
	content := "#!/bin/sh\n# ox pre-commit hook\nmake lint\n\n\necho 'after double blank'\n"
	tmpFile := filepath.Join(t.TempDir(), "hook")
	require.NoError(t, os.WriteFile(tmpFile, []byte(content), 0755))

	err := removeSageoxSections(tmpFile)
	require.NoError(t, err)

	result, err := os.ReadFile(tmpFile)
	require.NoError(t, err)
	resultStr := string(result)

	assert.NotContains(t, resultStr, "# ox pre-commit hook")
	assert.NotContains(t, resultStr, "make lint")
	assert.Contains(t, resultStr, "echo 'after double blank'")
}

