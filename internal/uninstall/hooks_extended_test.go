func TestAnalyzeHookFile_Unreadable(t *testing.T) {
	// nonexistent file should return error
	hasSageox, hasMixed, isEntireSox, err := analyzeHookFile("/nonexistent/path/hook")
	assert.Error(t, err)
	assert.False(t, hasSageox)
	assert.False(t, hasMixed)
	assert.False(t, isEntireSox)
}

func TestAnalyzeHookFile_AllMarkerTypes(t *testing.T) {
	tests := []struct {
		name       string
		content    string
		wantSageox bool
	}{
		{
			name:       "ox post-commit marker",
			content:    "#!/bin/sh\n# ox post-commit hook\necho done\n",
			wantSageox: true,
		},
		{
			name:       "ox prepare-commit-msg marker",
			content:    "#!/bin/sh\n# ox prepare-commit-msg hook\necho done\n",
			wantSageox: true,
		},
		{
			name:       "ox commit-msg marker",
			content:    "#!/bin/sh\n# ox commit-msg hook\necho done\n",
			wantSageox: true,
		},
		{
			name:       "Generated by ox marker",
			content:    "#!/bin/sh\n# Generated by ox\necho done\n",
			wantSageox: true,
		},
		{
			name:       "pre-commit.com in mixed hook",
			content:    "#!/bin/sh\n# ox pre-commit hook\nmake lint\n\n# pre-commit.com\npython hook\n",
			wantSageox: true,
		},
		{
			name:       "lint-staged in mixed hook",
			content:    "#!/bin/sh\n# ox pre-commit hook\nmake lint\n\n# lint-staged\nnpx lint-staged\n",
			wantSageox: true,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			tmpFile := filepath.Join(t.TempDir(), "hook")
			require.NoError(t, os.WriteFile(tmpFile, []byte(tt.content), 0755))

			gotSageox, _, _, err := analyzeHookFile(tmpFile)
			require.NoError(t, err)
			assert.Equal(t, tt.wantSageox, gotSageox)
		})
	}
}

func TestAnalyzeHookFile_NonSageoxCodeBeforeMarker(t *testing.T) {
	// code before any sageox marker should be detected as mixed
	content := "#!/bin/sh\necho 'user code'\n# ox pre-commit hook\nmake lint\n"
	tmpFile := filepath.Join(t.TempDir(), "hook")
	require.NoError(t, os.WriteFile(tmpFile, []byte(content), 0755))

	hasSageox, hasMixed, isEntireSox, err := analyzeHookFile(tmpFile)
	require.NoError(t, err)
	assert.True(t, hasSageox)
	assert.True(t, hasMixed)
	assert.False(t, isEntireSox)
}

