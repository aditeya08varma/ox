func TestFindSageoxHooks_DirectoryEntries(t *testing.T) {
	// subdirectories in .git/hooks/ should be skipped
	tmpDir := t.TempDir()
	hooksDir := filepath.Join(tmpDir, ".git", "hooks")
	require.NoError(t, os.MkdirAll(filepath.Join(hooksDir, "subdir"), 0755))

	// also add a real hook so we verify subdir is skipped
	require.NoError(t, os.WriteFile(
		filepath.Join(hooksDir, "pre-commit"),
		[]byte("#!/bin/sh\n# ox pre-commit hook\nmake lint\n"),
		0755,
	))

	items, err := FindSageoxHooks(tmpDir)
	require.NoError(t, err)
	assert.Len(t, items, 1)
	assert.Equal(t, "pre-commit", items[0].Name)
}
